// Pure rules for the `project` block (no node imports, so the browser bundle can use them too).
import type { ProjectLayout } from "./types.ts";

export const PROJECT_LAYOUT_DEFAULTS: ProjectLayout = { align: "left", size: "md", logoPosition: "left", showTitle: true };
export const PROJECT_ENUMS = {
  align: ["left", "center", "right"],
  size: ["sm", "md", "lg"],
  logoPosition: ["left", "top", "right", "hidden"],
} as const;
export const MAX_TITLE = 80;
export const MAX_SUBTITLE = 160;
/** Logos are shown small; a larger file is refused rather than shipped to every client. */
export const MAX_LOGO_BYTES = 1024 * 1024;
/** Extension allow-list. SVG is allowed because hosts must render it only through `<img>` (scripts do not run there). */
export const LOGO_TYPES: Readonly<Record<string, string>> = { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp", gif: "image/gif", svg: "image/svg+xml" };
/** Longest base64 text of a logo upload (4 characters per 3 bytes, with padding). */
export const MAX_LOGO_BASE64 = Math.ceil(MAX_LOGO_BYTES / 3) * 4;
/** Largest request body that may carry a logo upload (base64 plus the JSON around it). */
export const LOGO_BODY_BYTES = MAX_LOGO_BASE64 + 16 * 1024;

// Control characters, line breaks and bidi controls never belong in a one-line heading (ZWJ stays: emoji need it).
export const UNSAFE_TEXT = /[\p{Cc}\p{Zl}\p{Zp}؜​‎‏‪-‮⁠⁦-⁩﻿\u{e0000}-\u{e007f}]/u;
export const UNSAFE_TEXT_ALL = /[\p{Cc}\p{Zl}\p{Zp}؜​‎‏‪-‮⁠⁦-⁩﻿\u{e0000}-\u{e007f}]/gu;

/** Trimmed one-line text, or `undefined` when empty. `strict` throws instead of truncating or dropping. */
export function cleanText(v: unknown, max: number, label: string, strict: boolean): string | undefined {
  if (typeof v !== "string") {
    if (strict) throw new Error(`${label} must be text`);
    return undefined;
  }
  let t = v;
  if (UNSAFE_TEXT.test(t)) {
    if (strict) throw new Error(`${label} contains control characters`);
    t = t.replace(UNSAFE_TEXT_ALL, " ");
  }
  t = t.trim();
  if (!t) return undefined;
  const chars = [...t];
  if (chars.length > max) {
    if (strict) throw new Error(`${label} is longer than ${max} characters`);
    t = chars.slice(0, max).join("");
  }
  return t;
}

/** A logo upload: the name is only checked for its extension; the stored name is generated by the host. */
export interface LogoUpload {
  name: string;
  /** Standard base64 of the file bytes. */
  data: string;
}

/** The fields of a `setProject` message. `undefined` leaves a field, `null` clears it. `logo: null` removes the logo. */
export interface ProjectFields {
  title?: string | null;
  subtitle?: string | null;
  layout?: Partial<ProjectLayout>;
  logo?: LogoUpload | null;
}

const BASE64 = /^[A-Za-z0-9+/]+={0,2}$/;

/** Extension of a file name in lower case, or "". */
export const extOf = (name: string): string => (name.lastIndexOf(".") > 0 ? name.slice(name.lastIndexOf(".") + 1).toLowerCase() : "");

/** Strict check of a `setProject` message body; returns a clean copy (unknown fields refused) or the reason. */
export function validateProjectFields(raw: Record<string, unknown>): { ok: true; fields: ProjectFields } | { ok: false; reason: string } {
  for (const k of Object.keys(raw)) if (!["type", "title", "subtitle", "layout", "logo"].includes(k)) return { ok: false, reason: `unknown field: ${k}` };
  const fields: ProjectFields = {};
  try {
    for (const [k, max] of [["title", MAX_TITLE], ["subtitle", MAX_SUBTITLE]] as const) {
      const v = raw[k];
      if (v === undefined) continue;
      fields[k] = v === null ? null : (cleanText(v, max, k, true) ?? null);
    }
  } catch (e) {
    return { ok: false, reason: (e as Error).message };
  }
  if (raw.layout !== undefined) {
    const l = raw.layout;
    if (typeof l !== "object" || l === null || Array.isArray(l)) return { ok: false, reason: "layout must be an object" };
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(l)) {
      if (v === undefined) continue;
      if (k === "showTitle") {
        if (typeof v !== "boolean") return { ok: false, reason: "layout.showTitle must be true or false" };
      } else if (Object.hasOwn(PROJECT_ENUMS, k)) {
        const allowed = PROJECT_ENUMS[k as keyof typeof PROJECT_ENUMS] as readonly string[];
        if (typeof v !== "string" || !allowed.includes(v)) return { ok: false, reason: `layout.${k} must be one of ${allowed.join(", ")}` };
      } else return { ok: false, reason: `unknown layout field: ${k}` };
      out[k] = v;
    }
    fields.layout = out as Partial<ProjectLayout>;
  }
  if (raw.logo !== undefined) {
    const g = raw.logo;
    if (g === null) fields.logo = null;
    else {
      if (typeof g !== "object" || Array.isArray(g)) return { ok: false, reason: "logo must be null or an upload" };
      const u = g as Record<string, unknown>;
      if (Object.keys(u).some((k) => k !== "name" && k !== "data")) return { ok: false, reason: "unknown logo field" };
      if (typeof u.name !== "string" || u.name.length > 120 || UNSAFE_TEXT.test(u.name) || /[/\\:]/.test(u.name) || !Object.hasOwn(LOGO_TYPES, extOf(u.name))) return { ok: false, reason: "logo must be a png, jpg, webp, gif or svg file" };
      if (typeof u.data !== "string" || u.data.length === 0 || u.data.length > MAX_LOGO_BASE64 || u.data.length % 4 !== 0 || !BASE64.test(u.data)) return { ok: false, reason: `logo must be at most ${MAX_LOGO_BYTES / 1024} KiB` };
      fields.logo = { name: u.name, data: u.data };
    }
  }
  if (!Object.keys(fields).length) return { ok: false, reason: "nothing to change" };
  return { ok: true, fields };
}
